function validateForm(form) {
  if (!onFile(form)) return;
  const c = formChecker("West Virginia IT-104");
  c.bool(form, "exempt");
  if (form.exempt) return;
  c.nonNegInt(form, "exemptions");
  c.bool(form, "oneEarner");
  c.cents(form, "additionalWithholdingCents");
}

function compute({ taxYear, wagesCents, payPeriodsPerYear, form }) {
  const t = TABLES[taxYear];
  validateForm(form);
  const period = PERIOD_BY_COUNT[payPeriodsPerYear];
  if (!period || !t.exemptionCents[period]) {
    throw new Error(`West Virginia has no percentage table for ${payPeriodsPerYear} pay periods a year`);
  }
  const has = onFile(form);
  if (has && form.exempt) return { stateCents: 0, formBasis: "it-104-exempt", lines: {} };
  const set = has && form.oneEarner ? "oneEarner" : "twoEarner";
  const taxable = Math.max(0, wagesCents - (has ? form.exemptions ?? 0 : 0) * t.exemptionCents[period]);
  const tax = fromBaseTable(taxable, t.percentageTables[set][period]);
  const extra = has ? form.additionalWithholdingCents ?? 0 : 0;
  return {
    stateCents: Math.round(tax) + extra,
    formBasis: has ? "it-104" : "none-on-file-two-earner-zero",
    lines: { period, set, taxableCents: taxable },
  };
}

