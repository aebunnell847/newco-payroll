// Colorado income tax withholding: DR 1098, Colorado Withholding Worksheet
// for Employers (Colorado no longer publishes tables).
//
// 2026 (DR 1098, 10/21/25) - one flat rate:
//   2b = annual wages - line 2a allowance;  2c = 2b x 4.40%
//   2d = 2c / pay periods;                  2f = 2d + DR 0004 line 3 extra
//
// 2027 (DR 1098, 11/17/26) - graduated brackets, 3.7% to 8.4%:
//   1c = wages x pay periods;  1d = allowance;  1e = max(0, 1c - 1d)
//   2  = Column D + (1e - lower edge) x Column E   (Withholding Table)
//   3a = 2027 DR 0004 line 3 tax credit allowance (annual)
//   3b = max(0, 2 - 3a);  3c = 3b / pay periods
//   3e = 3c + 3d, the additional withholding (2027 DR 0004 line 4, or
//        line 3 of a 2022-2026 DR 0004: additionalWithholdingCents
//        either way)
// The table rows are generated by tools/state/generate_co.py from the PDF.
// The worksheet prints no effective date, only "for 2027", so the figures
// are keyed by tax year alone. "Lower edge": line 2b's text says subtract
// Column B ("at least": $25,001, $100,001, ...), but Column D only follows
// from the row below when the previous row's Column C ($25,000, $100,000,
// ...) is subtracted, and the Department's own DR 1098 Withholding
// Calculator (.xlsx, Nov. 2026 revision for 2027) subtracts Column C. This
// follows the calculator, including its row choice (bracket 2 from 1e of
// $25,001, so 1e of $25,000.50 stays at 3.7%). Flagged for review. No
// worked example is printed; the tests use vectors from evaluating the
// calculator's own formulas (tools/state/generate_co.py).
//
// Which allowance (2026 line 2a / 2027 line 1d):
//   - DR 0004 on file: its line 2 amount, "including an amount of zero".
//     A blank line 2 falls back to the W-4 amount below.
//   - Only a federal W-4, by its Step 1(c) status. 2026: $11,000 married
//     filing jointly or qualifying surviving spouse, $5,500 otherwise.
//     2027: $11,000 joint / surviving spouse, $8,500 head of household,
//     $5,500 single or married filing separately. A W-4 claiming exempt
//     means zero Colorado withholding.
//   - Neither: as if a W-4 with "single" ($5,500).
//   - A pre-2020 W-4 has no Step 1(c); DR 1098 doesn't say how to read one,
//     so this uses the single amount ($5,500), the higher-withholding
//     choice. (Flagged; a DR 0004 avoids the question.)
//
// DR 0004 input: { line2AllowanceCents?, taxCreditAllowanceCents? (2027
//   line 3, annual), additionalWithholdingCents? (2027 line 4 / 2022-2026
//   line 3, per pay period), denverWorker?, denverTd269? }. The 2026
//   worksheet has no tax credit line, so a nonzero taxCreditAllowanceCents
//   throws for 2026 rather than being silently ignored.
//
// Wages: federal income-tax wages - "Wages that are exempt from federal
// wage withholding are generally exempt from Colorado wage withholding"
// (Colorado Wage Withholding Tax Guide), so pre-tax 401(k) is excluded.
//
// Denver occupational privilege tax (Denver Tax Guide Topic 61): an
// employee who earns at least $500 in a calendar month for work in Denver
// owes $5.75 for that month, withheld by the employer (the employer's own
// $4.00 business tax isn't a withholding). Whether someone works in Denver
// is the employer's fact, so it's a field on the certificate object:
// `denverWorker`, plus `denverTd269` when the employee gave this employer a
// Form TD269 (another Denver employer already withholds it). It's withheld
// once a month, on the first pay date whose month-to-date pay reaches
// $500 - which needs month-to-date figures (the stored payroll run supplies
// them; without them this throws rather than guess). Returned as the
// DENVER_OPT locality. Aurora repealed its occupational privilege tax
// effective January 1, 2025, so there is nothing to withhold there.

const { formChecker, onFile } = require("./formUtil");

const TABLES = Object.freeze({
  2026: Object.freeze({
    rateBp: 440,
    jointAllowanceCents: 11_000_00,
    otherAllowanceCents: 5_500_00,
    denverOpt: Object.freeze({ employeeMonthlyCents: 5_75, monthlyThresholdCents: 500_00 }),
    sources: Object.freeze([
      "CO DOR, DR 1098 2026 Colorado Withholding Worksheet for Employers (10/21/25): https://tax.colorado.gov/sites/tax/files/documents/DR_1098_Colorado_Withholding_Worksheet_for_Employees.pdf",
      "CO DOR, Colorado Wage Withholding Tax Guide: https://tax.colorado.gov/withholding-tax-guide",
      "City and County of Denver, Tax Guide Topic 61, Occupational Privilege Taxes: https://www.denvergov.org/files/assets/public/v/2/finance/documents/treasury/tax-guides/taxguidetopic61_occupationalprivilegetaxes.pdf",
      "City of Aurora, Occupational Privilege Tax (repealed effective Jan. 1, 2025): https://www.auroragov.org/business_services/taxes/occupational_privilege_tax",
    ]),
  }),
  2027: Object.freeze({
    // Generated by tools/state/generate_co.py from DR 1098 (11/17/26).
    // Rows: [atLeastCents, subtractCents, baseCents, rateBasisPoints].
    rows: Object.freeze([
      [0, 0, 0, 370],
      [2500100, 2500000, 92500, 420],
      [10000100, 10000000, 407500, 440],
      [50000100, 50000000, 2167500, 740],
      [75000100, 75000000, 4017500, 790],
      [100000100, 100000000, 5992500, 840],
    ]),
    allowanceCents: Object.freeze({ marriedFilingJointly: 1100000, single: 550000, headOfHousehold: 850000 }),
    // Unchanged from 2026 (Denver Tax Guide Topic 61).
    denverOpt: Object.freeze({ employeeMonthlyCents: 5_75, monthlyThresholdCents: 500_00 }),
    sources: Object.freeze([
      "CO DOR, DR 1098 (11/17/26) 2027 Colorado Withholding Worksheet for Employers: https://tax.colorado.gov/sites/default/files/2026-11/DR_1098_2027.pdf",
      "CO DOR, DR 1098 Withholding Calculator, November 2026 Revision for use during 2027: https://tax.colorado.gov/sites/default/files/2026-11/DR_1098_Withholding_Calculator_Nov_2026_Revision_for_2027.xlsx",
      "CO DOR, DR 0004 (11/13/26) 2027 Colorado Employee Withholding Certificate: https://tax.colorado.gov/sites/default/files/2026-11/DR0004_2027.pdf",
      "CO DOR, Colorado Wage Withholding Tax Guide: https://tax.colorado.gov/withholding-tax-guide",
      "City and County of Denver, Tax Guide Topic 61, Occupational Privilege Taxes: https://www.denvergov.org/files/assets/public/v/2/finance/documents/treasury/tax-guides/taxguidetopic61_occupationalprivilegetaxes.pdf",
    ]),
  }),
});

const has = (form, key) => form[key] !== undefined && form[key] !== null;

function validateForm(form) {
  if (!onFile(form)) return;
  const c = formChecker("Colorado DR 0004");
  if (has(form, "line2AllowanceCents")) c.cents(form, "line2AllowanceCents");
  c.cents(form, "taxCreditAllowanceCents");
  c.cents(form, "additionalWithholdingCents");
  c.bool(form, "denverWorker");
  c.bool(form, "denverTd269");
}

/** Denver employee OPT for this paycheck: $5.75 once a month at $500. */
function denverOptCents(t, form, grossPayCents, monthToDate) {
  if (!onFile(form) || !form.denverWorker || form.denverTd269) return 0;
  if (!monthToDate) {
    throw new Error("Denver occupational privilege tax is monthly; month-to-date pay is required (use the stored payroll run)");
  }
  if (monthToDate.localities?.DENVER_OPT > 0) return 0;
  return monthToDate.grossCents + grossPayCents >= t.denverOpt.monthlyThresholdCents ? t.denverOpt.employeeMonthlyCents : 0;
}

function compute(args) {
  const t = TABLES[args.taxYear];
  const out = incomeTax(args);
  const opt = denverOptCents(t, args.form, args.grossPayCents ?? args.wagesCents, args.monthToDate);
  return opt ? { ...out, localities: { DENVER_OPT: opt } } : out;
}

// The Denver flags can sit on the object without a DR 0004 being filed;
// only DR 0004 fields make it one.
const isDr0004 = (form) =>
  onFile(form) && ["line2AllowanceCents", "taxCreditAllowanceCents", "additionalWithholdingCents"].some((k) => has(form, k));

/** The W-4-based allowance for a Step 1(c) status, by year's worksheet. */
function w4Allowance(t, taxYear, status) {
  if (taxYear === 2026) return status === "marriedFilingJointly" ? t.jointAllowanceCents : t.otherAllowanceCents;
  return t.allowanceCents[status] ?? t.allowanceCents.single;
}

function incomeTax({ taxYear, wagesCents, payPeriodsPerYear, form, federalW4 = null }) {
  const t = TABLES[taxYear];
  validateForm(form);
  const dr0004 = isDr0004(form);
  const credit = dr0004 ? form.taxCreditAllowanceCents ?? 0 : 0;
  if (taxYear === 2026 && credit > 0) {
    throw new Error("Colorado DR 0004: taxCreditAllowanceCents is a 2027 DR 0004 line; the 2026 DR 1098 worksheet has no tax credit allowance");
  }
  let allowance;
  let formBasis;
  if (dr0004 && has(form, "line2AllowanceCents")) {
    allowance = form.line2AllowanceCents;
    formBasis = "dr-0004";
  } else if (federalW4) {
    if (!dr0004 && federalW4.exempt) return { stateCents: 0, formBasis: "federal-w4-exempt", lines: {} };
    // A pre-2020 W-4 has no Step 1(c): single (flagged, see above).
    allowance = w4Allowance(t, taxYear, federalW4.formYear >= 2020 ? federalW4.filingStatus : "single");
    formBasis = dr0004 ? "dr-0004-line-2-blank-federal-w4" : "federal-w4";
  } else {
    allowance = w4Allowance(t, taxYear, "single");
    formBasis = dr0004 ? "dr-0004-line-2-blank-single" : "none-on-file-single";
  }
  const annual = wagesCents * payPeriodsPerYear;
  const extra = dr0004 ? form.additionalWithholdingCents ?? 0 : 0;

  if (taxYear === 2026) {
    const line2b = Math.max(0, annual - allowance);
    const line2c = (line2b * t.rateBp) / 10_000;
    return {
      stateCents: Math.round(line2c / payPeriodsPerYear) + extra,
      formBasis,
      lines: { line1cCents: annual, line2aCents: allowance, line2bCents: line2b, line2cCents: line2c },
    };
  }

  const line1e = Math.max(0, annual - allowance);
  // The calculator's row choice: the last row whose Column B line 1e reaches.
  let row = t.rows[0];
  for (const r of t.rows) if (line1e >= r[0]) row = r;
  const [, subtract, base, rateBp] = row;
  const line2 = base + ((line1e - subtract) * rateBp) / 10_000;
  const line3b = Math.max(0, line2 - credit);
  const line3c = line3b / payPeriodsPerYear;
  return {
    stateCents: Math.round(line3c) + extra,
    formBasis,
    lines: {
      line1cCents: annual,
      line1dCents: allowance,
      line1eCents: line1e,
      line2Cents: line2,
      line3aCents: credit,
      line3bCents: line3b,
      line3cCents: line3c,
      line3dCents: extra,
    },
  };
}

module.exports = {
  code: "CO",
  name: "Colorado",
  wageBasis: "federal-income-tax-wages",
  years: Object.keys(TABLES).map(Number),
  TABLES,
  validateForm,
  compute,
};
