function validateForm(form) {
  if (!onFile(form)) return;
  const c = formChecker("Nebraska W-4N");
  c.bool(form, "exempt");
  if (form.exempt) return;
  c.oneOf(form, "filingStatus", ["single", "married"]);
  c.nonNegInt(form, "allowances");
  c.cents(form, "additionalWithholdingCents");
}

function compute({ taxYear, wagesCents, payPeriodsPerYear, form, federalW4 = null }) {
  const t = TABLES[taxYear];
  validateForm(form);
  const period = PERIOD_BY_COUNT[payPeriodsPerYear];
  if (!period) throw new Error(`Nebraska has no percentage table for ${payPeriodsPerYear} pay periods a year`);
  const has = onFile(form);
  if (has && form.exempt) return { stateCents: 0, formBasis: "w-4n-exempt", lines: {} };
  let status = "single";
  let allowances = 0;
  let formBasis = "none-on-file-single-zero";
  if (has) {
    status = form.filingStatus;
    allowances = form.allowances ?? 0;
    formBasis = "w-4n";
  } else if (federalW4 && federalW4.formYear < 2020) {
    status = federalW4.maritalStatus === "married" ? "married" : "single";
    allowances = federalW4.allowances ?? 0;
    formBasis = "federal-w4-pre-2020";
  }
  const taxFor = (s, n) =>
    fromBaseTable(Math.max(0, wagesCents - n * t.allowanceCents[period]), t.percentageTables[period][s]);
  let tax = taxFor(status, allowances);
  let minimumApplied = false;
  if (tax < (wagesCents * t.minimumShareBp) / 10_000) {
    const floor = 0.5 * (status === "married" ? taxFor("married", 2) : taxFor("single", 1));
    if (floor > tax) {
      tax = floor;
      minimumApplied = true;
    }
  }
  const extra = has ? form.additionalWithholdingCents ?? 0 : 0;
  return {
    stateCents: Math.round(tax) + extra,
    formBasis,
    lines: { period, status, allowances, minimumApplied },
  };
}

