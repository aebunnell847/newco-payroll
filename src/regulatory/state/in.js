// Indiana state and county income tax withholding: Departmental Notice #1,
// "How to Compute Withholding for State and County Income Tax" (R47 / 10-26,
// effective Oct. 1, 2026).
//   taxable = wages - deduction constants (Tables A, B, C)
//   state   = taxable x 2.95%
//   county  = taxable x the county's rate
// Deduction constants are the annual exemption amounts divided by the pay
// periods - $1,000 per personal exemption (WH-4 line 5), $1,500 per
// additional dependent exemption (lines 6 and 7), $3,000 per adopted child
// (line 8) - with "Daily" divided by 365, as in the printed tables. Each
// table's constant is rounded to the cent, as in the Notice's example.
//
// County: by the employee's Indiana county of residence on Jan. 1; for an
// out-of-state resident, the Indiana county of principal employment on
// Jan. 1. Both come from Form WH-4. County tax is returned as a locality
// ("IN-<county code>"), since it's reported separately on the W-2.
// The county table below is generated by tools/state/generate_in_counties.py
// from the Notice. One county (Boone) changed its rate on Oct. 1, 2026,
// from 0.017 to 0.0171: pay dates before then use 0.017 from the Jan. 1,
// 2026 Notice (R46 / 01-26, as archived Jan. 16, 2026), which also
// confirms every other county's rate, the 2.95% state rate and the
// exemption amounts were the same all year.
//
// WH-4 input: { personalExemptions (line 5), additionalDependentExemptions
//   (line 6), firstTimeDependentExemptions (line 7), adoptedDependentExemptions
//   (line 8), countyOfResidence?, countyOfPrincipalEmployment? (two-digit
//   county codes, or null for "not applicable"), additionalStateCents?,
//   additionalCountyCents? }
// No WH-4 on file: Indiana's publications don't say. This withholds state
// tax with no exemptions (the higher-withholding choice) and NO county tax,
// because the county can't be known without the WH-4 - flagged in
// formBasis ("none-on-file-no-county") so payroll can chase the form.
//
// Wages: federal income-tax wages. Indiana adjusted gross income starts
// from federal AGI (IC 6-3-1-3.5), which excludes pre-tax 401(k) deferrals.
//
// The Notice's worked example ($800 weekly, 5 + 3 + 1 + 2 exemptions, county
// rate 1%: taxable $473.08, state $13.96, county $4.73) is in the tests.

