const COUNTY_CODE = /^\d{2}$/;

function validateForm(form) {
  if (!onFile(form)) return;
  const c = formChecker("Indiana WH-4");
  for (const k of ["personalExemptions", "additionalDependentExemptions", "firstTimeDependentExemptions", "adoptedDependentExemptions"]) {
    c.nonNegInt(form, k);
  }
  for (const k of ["countyOfResidence", "countyOfPrincipalEmployment"]) {
    const v = form[k];
    if (v !== undefined && v !== null && !(COUNTY_CODE.test(v) && COUNTIES[v])) {
      c.fail(`${k} must be a two-digit Indiana county code (01-92) or null`);
    }
  }
  c.cents(form, "additionalStateCents");
  c.cents(form, "additionalCountyCents");
}

function constant(count, annualCents, period) {
  return Math.round((count * annualCents) / DIVISOR[period]);
}

function compute({ taxYear, wagesCents, payPeriodsPerYear, form, payDate }) {
  const t = TABLES[taxYear];
  validateForm(form);
  const period = PERIOD_BY_COUNT[payPeriodsPerYear];
  if (!period) throw new Error(`Indiana deduction constants have no column for ${payPeriodsPerYear} pay periods a year`);
  const has = onFile(form);
  const f = has ? form : {};
  const deduction =
    constant(f.personalExemptions ?? 0, t.personalExemptionCents, period) +
    constant(f.additionalDependentExemptions ?? 0, t.dependentExemptionCents, period) +
    constant(f.firstTimeDependentExemptions ?? 0, t.dependentExemptionCents, period) +
    constant(f.adoptedDependentExemptions ?? 0, t.adoptedExemptionCents, period);
  const taxable = Math.max(0, wagesCents - deduction);
  const stateCents = Math.round((taxable * t.stateRateBp) / 10_000) + (f.additionalStateCents ?? 0);

  const countyCode = f.countyOfResidence ?? f.countyOfPrincipalEmployment ?? null;
  const localities = {};
  if (countyCode) {
    const county = t.counties[countyCode];
    let ratePpm = county.ratePpm;
    if (county.changedOct2026) {
      if (typeof payDate !== "string" || !/^\d{4}-\d{2}-\d{2}$/.test(payDate)) {
        throw new Error(`${county.name} County (Indiana) withholding needs the pay date: its rate changed on ${t.countyChangeDate}`);
      }
      if (payDate < t.countyChangeDate) ratePpm = t.countyRatePpmBeforeChange[countyCode];
    }
    localities[`IN-${countyCode}`] = Math.round((taxable * ratePpm) / 1_000_000) + (f.additionalCountyCents ?? 0);
  }
  return {
    stateCents,
    localities,
    formBasis: !has ? "none-on-file-no-county" : countyCode ? "wh-4" : "wh-4-no-indiana-county",
    lines: { period, deductionCents: deduction, taxableCents: taxable, county: countyCode },
  };
}

