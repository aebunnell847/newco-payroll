// Virginia income tax withholding: Virginia Tax's withholding-table
// package, "Formula for Computing Tax to be Withheld":
//   T = G x P - [standard deduction + E1 x $930 + E2 x $800]
//   W = 2% to $3,000; $60 + 3% to $5,000; $120 + 5% to $17,000;
//       $720 + 5.75% over $17,000
//   W/H = W / P
// P for daily payroll is 300 (the Department's Pay Period Conversion
// Table). The Department's example rounds W to whole dollars before
// dividing; this does the same, and matches it.
//
// Editions, keyed by the year of the pay date:
//   2026 - "Withholding Tables for Wages Paid after July 1, 2025" (now
//          published as the July 2025 - December 2026 package): $8,750
//          standard deduction. Example: $2,649 semimonthly, E1 = 5 ->
//          W $2,628, $109.50.
//   2027 - "Withholding Table for Wages Paid January 1, 2027, to December
//          31, 2027" ("Effective for wages paid after January 1, 2027, but
//          before January 1, 2028"): $9,200 standard deduction, "for
//          taxable year 2027 only"; "New tables for taxable years 2028 &
//          2029 will be published in the Fall of 2027", so 2028 throws
//          until then. Example: same employee -> W $2,602, $108.42.
// Only the standard deduction differs between the two. The figures are
// generated from each PDF by tools/state/generate_va.py, which also checks
// the worked example and that every printed Daily / Weekly / Semi-Monthly /
// Biweekly / Monthly table cell (5,753 per edition) reproduces from the
// formula. Both editions print the E2 amount as "800" (no "$"); the
// generator reads it as dollars, as the legend and the 2026 code did.
//
// VA-4 input: { personalExemptions (E1: self, spouse, dependents),
//   ageBlindExemptions (E2), additionalWithholdingCents?, exempt? }.
// "You may not substitute federal certificates (Forms W-4 or W-4P)."
// No VA-4 on file: "withhold Virginia income tax as if no exemptions had
// been claimed" (Income Tax Withholding Guide for Employers).
//
// Wages: "Payments that are exempt from federal withholding are also
// exempt from Virginia withholding" (Guide), so pre-tax 401(k) is excluded.

const { formChecker, onFile } = require("./formUtil");
const { fromBaseTable } = require("./brackets");

const TABLES = Object.freeze({
  // Generated by tools/state/generate_va.py (wages paid after July 1, 2025).
  2026: Object.freeze({
    standardDeductionCents: 8_750_00,
    personalExemptionCents: 930_00,
    ageBlindExemptionCents: 800_00,
    dailyPeriods: 300,
    annualTable: Object.freeze([
      [0, 0, 200],
      [3_000_00, 60_00, 300],
      [5_000_00, 120_00, 500],
      [17_000_00, 720_00, 575],
    ]),
    sources: Object.freeze([
      "Virginia Tax, Withholding Tables for Wages Paid after July 1, 2025 (July 2025 - December 2026 package): https://www.tax.virginia.gov/sites/default/files/taxforms/withholding/any/employer-withholding-tables-july-2025-december-2026-any.pdf",
      "Virginia Tax, Income Tax Withholding Guide for Employers: https://www.tax.virginia.gov/sites/default/files/vatax-pdf/employer-withholding-instructions.pdf",
      "Virginia Tax, Form VA-4: https://www.tax.virginia.gov/sites/default/files/taxforms/withholding/any/va-4-any.pdf",
    ]),
  }),
  // Generated by tools/state/generate_va.py (wages paid January 1, 2027, to
  // December 31, 2027).
  2027: Object.freeze({
    standardDeductionCents: 9_200_00,
    personalExemptionCents: 930_00,
    ageBlindExemptionCents: 800_00,
    dailyPeriods: 300,
    annualTable: Object.freeze([
      [0, 0, 200],
      [3_000_00, 60_00, 300],
      [5_000_00, 120_00, 500],
      [17_000_00, 720_00, 575],
    ]),
    sources: Object.freeze([
      "Virginia Tax, Withholding Table for Wages Paid January 1, 2027, to December 31, 2027: https://www.tax.virginia.gov/sites/default/files/taxforms/withholding/any/employer-withholding-tables-january-2027-and-later-any.pdf",
      "Virginia Tax, Income Tax Withholding Guide for Employers: https://www.tax.virginia.gov/sites/default/files/vatax-pdf/employer-withholding-instructions.pdf",
      "Virginia Tax, Form VA-4: https://www.tax.virginia.gov/sites/default/files/taxforms/withholding/any/va-4-any.pdf",
    ]),
  }),
});

function validateForm(form) {
  if (!onFile(form)) return;
  const c = formChecker("Virginia VA-4");
  c.nonNegInt(form, "personalExemptions");
  c.nonNegInt(form, "ageBlindExemptions");
  c.cents(form, "additionalWithholdingCents");
  c.bool(form, "exempt");
}

function compute({ taxYear, wagesCents, payPeriodsPerYear, form }) {
  const t = TABLES[taxYear];
  validateForm(form);
  const has = onFile(form);
  if (has && form.exempt) return { stateCents: 0, formBasis: "va-4-exempt", lines: {} };
  const P = payPeriodsPerYear === 260 ? t.dailyPeriods : payPeriodsPerYear;
  const E1 = has ? form.personalExemptions ?? 0 : 0;
  const E2 = has ? form.ageBlindExemptions ?? 0 : 0;
  const T = Math.max(0, wagesCents * P - (t.standardDeductionCents + E1 * t.personalExemptionCents + E2 * t.ageBlindExemptionCents));
  const W = Math.round(fromBaseTable(T, t.annualTable) / 100) * 100;
  const extra = has ? form.additionalWithholdingCents ?? 0 : 0;
  return {
    stateCents: Math.round(W / P) + extra,
    formBasis: has ? "va-4" : "none-on-file-no-exemptions",
    lines: { P, T, W },
  };
}

module.exports = {
  code: "VA",
  name: "Virginia",
  wageBasis: "federal-income-tax-wages",
  years: Object.keys(TABLES).map(Number),
  TABLES,
  validateForm,
  compute,
};
