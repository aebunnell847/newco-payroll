function validateForm(form) {
  if (!onFile(form)) return;
  const c = formChecker("Maryland MW507");
  c.bool(form, "exempt");
  if (form.exempt) return;
  if (form.county === "delaware" || form.county === "nonreciprocal") {
    c.fail("residents working in Delaware or another nonreciprocal state need the Comptroller's Delaware table, which isn't encoded yet");
  }
  c.oneOf(form, "county", Object.keys(COUNTIES));
  c.oneOf(form, "filingStatus", ["single", "married", "headOfHousehold", "marriedWithholdAtSingle"]);
  c.nonNegInt(form, "exemptions");
  c.cents(form, "additionalWithholdingCents");
}

function compute({ taxYear, wagesCents, payPeriodsPerYear, form }) {
  const t = TABLES[taxYear];
  validateForm(form);
  const period = PERIOD_BY_COUNT[payPeriodsPerYear];
  if (!period || period === "semiannual") {
    throw new Error(`Maryland has no percentage table for ${payPeriodsPerYear} pay periods a year`);
  }
  const has = onFile(form);
  if (has && form.exempt) return { stateCents: 0, formBasis: "mw507-exempt", lines: {} };
  const status = has && (form.filingStatus === "married" || form.filingStatus === "headOfHousehold") ? "joint" : "single";
  const exemptions = has ? form.exemptions ?? 0 : 0;

  // Any table gives the same deductions (they're state amounts); use it to
  // find annualized taxable income for tiered counties.
  const anyPeriod = t.rateTables["320"][period];
  const taxable = Math.max(0, wagesCents - anyPeriod.standardDeductionCents - exemptions * anyPeriod.exemptionCents);
  let tableCode = t.noCertificateTable;
  if (has) {
    const c = t.counties[form.county];
    tableCode = typeof c === "string" ? c : c[status].find(([upTo]) => taxable * payPeriodsPerYear <= upTo)[1];
  }
  const p = t.rateTables[tableCode][period];
  if (wagesCents < p.floorCents) {
    return { stateCents: 0, formBasis: has ? "mw507" : "none-on-file-single-zero-highest-local", lines: { period, localRateBp: Number(tableCode), belowFloor: true } };
  }
  const tax = fromBaseTable(taxable, p[status]);
  const extra = has ? form.additionalWithholdingCents ?? 0 : 0;
  return {
    stateCents: Math.round(tax) + extra,
    formBasis: has ? "mw507" : "none-on-file-single-zero-highest-local",
    lines: { period, status, localRateBp: Number(tableCode), taxableCents: taxable },
  };
}

