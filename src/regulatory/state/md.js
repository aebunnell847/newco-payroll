// Maryland state and local (county) income tax withholding: the
// Comptroller's 2026 "Percentage method of withholding for X.XX PERCENT
// LOCAL INCOME TAX" tables, one per local rate (pm225 ... pm330):
//   taxable = wages - standard deduction for the period - exemptions x
//             the period's exemption amount ($3,400 and $3,200 a year)
//   the period's table: (a) married filing joint / head of household or
//   (b) single / married filing separately; its rates combine Maryland's
//   marginal state rates (4.75% ... 6.50%) and the local rate
//   no withholding when gross wages are under the table's floor
// Maryland withholds state and local tax together (one amount, reported
// together), so the whole amount is `stateCents`; `lines.localRateBp` says
// which local table was used.
//
// Tables generated by tools/state/generate_md.py from the nine PDFs. The
// PDFs carry ten print defects, which the generator corrects and reports
// every run (a row start that disagrees with its "of excess over", a rate
// that isn't state + local, bases that don't follow from their bracket).
// The Comptroller prints no worked example; the tests pin each table's
// rates to state + local and every base to the bracket below it.
//
// Locality (Comptroller's rates page, 2026 tax year): by the employee's
// county of residence (MW507). Two counties have tiered 2026 rates and link
// several tables; this picks the one whose tier holds the employee's
// annualized taxable income (Anne Arundel: 2.70% / 2.94% / 3.20% at
// $50,000 / $400,000 single, $75,000 / $480,000 joint; Frederick: 2.25% /
// 2.75% / 2.96% / 3.20% at $25,000 / $50,000 / $150,000 single, $25,000 /
// $100,000 / $250,000 joint). Each table's rate equals or slightly exceeds
// the county rate, as the Comptroller intends ("without going below").
// Nonresidents use the nonresident table (no local tax; the special 2.25%
// nonresident tax). Residents working in Delaware or another nonreciprocal
// state need the Comptroller's separate Delaware table, not encoded: throws.
//
// MW507 input: { county (see COUNTIES), filingStatus: "single" | "married"
//   | "headOfHousehold" | "marriedWithholdAtSingle", exemptions,
//   additionalWithholdingCents?, exempt? }.
// No MW507 on file: the tables don't say; this withholds as single with no
// exemptions at the highest local table (3.30%) - the higher-withholding
// choice, since the county is unknown. Flagged.
//
// Wages: federal income-tax wages; Maryland income starts from federal AGI,
// so pre-tax 401(k) is excluded (not addressed in the tables themselves).

