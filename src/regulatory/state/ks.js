// Kansas income tax withholding: "Tables for Percentage Method of Kansas
// Withholding (For wages paid on and after July 1, 2024)" with the KW-100
// Withholding Tax Guide. These are still the Department's current tables
// (no later edition), so they cover 2025 and 2026 pay dates here.
//   1. allowance amount = the employee's Kansas personal exemptions / pay
//      periods: $9,160 single / HoH / married filing separately, $18,320
//      married filing jointly, +$2,320 head of household, +$2,320 per
//      dependent (KW-100)
//   2. net = wages - allowance amount
//   3. the period's table (single incl. HoH, or married)
// The tables are generated by tools/state/generate_ks.py from the PDF. The
// KW-100 example (Esmeralda: $2,000 semimonthly, married, spouse no
// income, 1 dependent -> $41.44) is in the tests. Kansas lets employers
// round to the dollar; this keeps the cent, as the example's answer does.
//
// K-4 input: { filingStatus: "single" | "married" | "headOfHousehold",
//   personalExemptions (1, or 2 for a spouse with no income), dependents,
//   additionalWithholdingCents? }.
// No K-4 on file: "withhold wages at the single rate with no allowances"
// (KW-100).
//
// Wages: "If your cafeteria, 401K ... plan is considered to be wages by the
// federal government and federal income tax withholding is required,
// Kansas withholding is also required" (KW-100) - so pre-tax 401(k),
// which isn't federal income-tax wages, is excluded.

